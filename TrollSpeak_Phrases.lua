local function ResolveFiller(text)
    return (text:gsub("{filler}", function()
        return TrollSpeakFillers[math.random(#TrollSpeakFillers)]
    end))
end

function TrollSpeak_GetPhrase(lowerTrimmed)
    local value = TrollSpeakPhrases[lowerTrimmed]
    if not value then return nil end

    if value:sub(1, 1) == "@" then
        local pool = TrollSpeakPools[value]
        if not pool then return nil end
        return ResolveFiller(pool[math.random(#pool)])
    end

    return ResolveFiller(value)
end
